import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import {
    ABOUT_COMPONENT_KINDS,
    ABOUT_HEADLESS,
    ABOUT_HOW_IT_WORKS,
    ABOUT_PHILOSOPHY,
    ABOUT_SHARED_CORE,
    ABOUT_SOURCE_LINK,
} from "../src/App/Pages/AboutPage/AboutPage.const.ts";

const OUTPUT_FILE = fileURLToPath(new URL("../../README.md", import.meta.url));
const SITE_URL = "https://ss-components.vercel.app";

const PACKAGES = [
    { folder: "components-solid", name: "@thewaver/ss-components-solid", role: "the components, for Solid" },
    { folder: "components-react", name: "@thewaver/ss-components-react", role: "the components, for React" },
    { folder: "components-vue", name: "@thewaver/ss-components-vue", role: "the components, for Vue" },
    { folder: "components-svelte", name: "@thewaver/ss-components-svelte", role: "the components, for Svelte" },
    {
        folder: "components",
        name: "@thewaver/ss-components",
        role: "the framework-free core the four share, installed along with them",
    },
    {
        folder: "utils",
        name: "@thewaver/ss-utils",
        role: "geometry, CSS, SVG and DOM helpers the core is built on, usable on its own",
    },
];

const toMarkdown = (inlines) =>
    inlines.map((inline) => (typeof inline === "string" ? inline : `[${inline.text}](${inline.href})`)).join("");

const README = `<!-- Generated by \`npm run update:readme\` from the Playground's About page text
(playground/src/App/Pages/AboutPage/AboutPage.const.ts). Edit that file and run the script; edits here are lost. -->

# ss-components

A free, ${toMarkdown([ABOUT_SOURCE_LINK])} library of interface components for Solid, React, Vue and Svelte:
${ABOUT_COMPONENT_KINDS}.

${ABOUT_HEADLESS}

The same components exist in all four frameworks, with the same names and the same props. ${ABOUT_SHARED_CORE}

Live, editable examples and a full prop table for every component are at **[${SITE_URL.replace("https://", "")}](${SITE_URL})**.

## Packages

| Package | What it is |
| ------- | ---------- |
${PACKAGES.map((pkg) => `| [\`${pkg.name}\`](${pkg.folder}/README.md) | ${pkg.role} |`).join("\n")}

Install the one for your framework; it brings the core and names the rest as peer dependencies.

**Browser only: drawing these components on a server — Next.js, Nuxt, SvelteKit, SolidStart — is not tested.**

## Philosophy

${ABOUT_PHILOSOPHY.map((item) => `- ${toMarkdown(item)}`).join("\n")}

## How it works

${ABOUT_HOW_IT_WORKS}

## License

[MIT](LICENSE).
`;

await writeFile(OUTPUT_FILE, README);
